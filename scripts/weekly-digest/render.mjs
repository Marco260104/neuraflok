function renderSection(title, rows) {
  const items = rows.length
    ? rows.map(row => `- #${row.number} ${row.title}${row.by ? ` (@${row.by})` : ''}`)
    : ['Nothing right now.'];
  return [`### ${title}`, '', ...items, ''];
}

export function renderDigest({ date, prs, issues }) {
  return [
    `Week of ${date}. Generated by the weekly digest workflow; the previous digest is closed automatically.`,
    '',
    ...renderSection('Green and waiting for a review', prs.filter(row => row.state === 'review')),
    ...renderSection('Waiting for their authors', prs.filter(row => row.state === 'author')),
    ...renderSection('New issues without an answer yet', issues.filter(row => row.state === 'unanswered')),
    ...renderSection('Waiting for their reporters (needs-info)', issues.filter(row => row.state === 'needs-info'))
  ].join('\n');
}
